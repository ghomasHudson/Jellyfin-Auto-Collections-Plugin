"""Assemble the pinned Python and Chromium runtime for the release ZIP."""

import hashlib
import json
import shutil
import sys
import tempfile
import urllib.request
from pathlib import Path
from zipfile import ZipFile


def main(root: Path) -> None:
    python = root / "python/lib/python3.12"
    site = python / "site-packages"
    # Keep urlrender's tested launch/context options and waits except for enabling
    # the sandbox. Add a capture hook so the helper needn't serialize the whole DOM.
    renderer = site / "urlrender/renderer.py"
    text = renderer.read_text(encoding="utf-8")
    replacements = [
        ('                args=[\n                    "--no-sandbox",\n',
         "                chromium_sandbox=True,\n                args=[\n"),
        ("        wait_for_selector: Optional[str] = None,\n",
         "        wait_for_selector: Optional[str] = None,\n        capture=None,\n"),
        ("                page = context.new_page()\n",
         "                page = context.new_page()\n"
         "                read_document = capture(page) if capture is not None else None\n"),
        ("                html = page.content()\n",
         "                if read_document is not None:\n"
         "                    return read_document()\n\n"
         "                html = page.content()\n"),
    ]
    for old, new in replacements:
        if text.count(old) != 1:
            raise ValueError("urlrender patch no longer matches the pinned wheel")
        text = text.replace(old, new)
    if "--no-sandbox" in text:
        raise ValueError("urlrender still disables Chromium sandboxing")
    renderer.write_text(text, encoding="utf-8")

    # Leave only the stdlib and installed runtime wheels, not the package manager,
    # toolchain files, generated bytecode, or unused optional extension modules.
    for path in (
        python / "ensurepip",
        python / "test",
        site / "pip",
        site / "bin",
        *site.glob("pip-*.dist-info"),
        *python.glob("config-*"),
        *python.rglob("__pycache__"),
    ):
        shutil.rmtree(path, ignore_errors=not path.exists())
    for module in ("_curses", "_curses_panel", "_gdbm", "_tkinter", "nis", "readline"):
        for path in (python / "lib-dynload").glob(f"{module}.*.so"):
            path.unlink()

    shutil.copyfile(python / "LICENSE.txt", root / "licenses/CPython.txt")
    shutil.copyfile("requirements.txt", root / "licenses/python-requirements.txt")

    # Use the exact browser revision bundled with the verified Playwright version,
    # but download just Headless Shell (not regular Chrome, ffmpeg, or Firefox).
    chromium_version = "159.0.8154.6"
    revision = "1255"
    manifest = json.loads((site / "playwright/driver/package/browsers.json").read_text())
    shell = next(browser for browser in manifest["browsers"] if browser["name"] == "chromium-headless-shell")
    if shell["revision"] != revision or shell["browserVersion"] != chromium_version:
        raise ValueError("Playwright's Chromium revision changed")
    url = f"https://storage.googleapis.com/chrome-for-testing-public/{chromium_version}/linux64/chrome-headless-shell-linux64.zip"
    sha256 = "77a6442fd3c8acd3bef9e1067fc26f5ef464277d22f0e8cb58dc3e4077a3e458"
    with tempfile.TemporaryFile() as downloaded:
        with urllib.request.urlopen(url, timeout=60) as response:
            shutil.copyfileobj(response, downloaded)
        downloaded.seek(0)
        if hashlib.file_digest(downloaded, "sha256").hexdigest() != sha256:
            raise ValueError("Unexpected Chromium download digest")
        with ZipFile(downloaded) as archive:
            archive.extractall(root / f"browsers/chromium_headless_shell-{revision}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
